'use strict';

// server/utils/verificationTokens.js
//
// ─────────────────────────────────────────────────────────────────────────────
// Server-owned verification tokens for public QR verification.
//
// WHY A TOKEN AT ALL
//   The QR code on a certificate used to carry the document's CouchDB `_id`.
//   Those ids are sequential-ish and enumerable (`CERT-2026-108273`,
//   `brgy_clearance_1788929049299_xx1y2z`), so anybody could walk the id
//   space and probe the public verification endpoint for other people's
//   certificates.
//
//   A verification token is a 256-bit cryptographically random secret. It is
//   generated by the SERVER (never by the client, never from resident data),
//   it is handed to the issuing device exactly once, and only its SHA-256
//   hash is stored. The document id of the verification record IS the hash, so
//   a lookup is a direct `db.get()` — no index, no query, and no field that
//   could leak the secret through a view or a Mango selector.
//
// SECURITY PROPERTIES
//   * The raw token is never written to the verification registry.
//   * The raw token is never logged (the controller logs only its length and
//     the record id).
//   * Verification records are server-owned: the sync proxy refuses to let a
//     client write them (see server/index.js), so a device cannot mint its own
//     "valid" certificate.
// ─────────────────────────────────────────────────────────────────────────────

const crypto = require('crypto');

/** 32 bytes = 256 bits of entropy. */
const TOKEN_BYTES = 32;
/** base64url → 43 URL-safe characters, no padding, no '+' or '/'. */
const TOKEN_ENCODING = 'base64url';
/** The exact shape of a token we issued. */
const TOKEN_PATTERN = /^[A-Za-z0-9_-]{43}$/;

const VERIFICATION_RECORD_PREFIX = 'certverify_';
const VERIFICATION_RECORD_TYPE = 'certificate_verification';
const VERIFICATION_ALIAS_PREFIX = 'certverify_cert_';
const VERIFICATION_ALIAS_TYPE = 'certificate_verification_index';

/**
 * Generate a cryptographically secure verification token.
 * @returns {string} 43-character base64url secret
 */
function generateVerificationToken() {
  return crypto.randomBytes(TOKEN_BYTES).toString(TOKEN_ENCODING);
}

/**
 * Hash a verification token with SHA-256.
 * Only this hash is ever persisted.
 * @param {string} token
 * @returns {string} 64-character lowercase hex digest
 */
function hashVerificationToken(token) {
  return crypto.createHash('sha256').update(String(token ?? ''), 'utf8').digest('hex');
}

/**
 * True when the value has the exact shape of a token this server issues.
 * This is a FORMAT check only — it proves nothing about authenticity.
 * @param {unknown} token
 * @returns {boolean}
 */
function isValidVerificationToken(token) {
  return typeof token === 'string' && TOKEN_PATTERN.test(token);
}

/**
 * The document id of the verification record for a token.
 * Because the id is the token hash, a lookup needs no index and two
 * different tokens can never collide on the same document.
 * @param {string} token
 * @returns {string}
 */
function verificationRecordId(token) {
  return `${VERIFICATION_RECORD_PREFIX}${hashVerificationToken(token)}`;
}

/**
 * The document id of the ALIAS record that points from a certificate to its
 * verification record.
 *
 * Why an alias is needed: the record id is the token hash, so the token can
 * be found in one direct lookup — but a lookup BY CERTIFICATE (needed to
 * revoke, or to detect that a certificate already has a token) has no key.
 * The alias supplies that key without needing a Mango index: it is a second
 * document whose id is the hash of the certificate id and whose body holds
 * the token hash. Both lookups stay O(1) `db.get()` calls.
 *
 * @param {string} certificateId
 * @returns {string}
 */
function verificationAliasId(certificateId) {
  return `${VERIFICATION_ALIAS_PREFIX}${crypto
    .createHash('sha256')
    .update(String(certificateId ?? ''), 'utf8')
    .digest('hex')}`;
}

/**
 * Build the alias record for a certificate.
 * @param {object} params
 * @param {string} params.certificateId
 * @param {string} params.token
 * @param {string} [params.now]
 * @returns {object}
 */
function buildVerificationAlias({ certificateId, token, now = null } = {}) {
  const timestamp = now || new Date().toISOString();
  return {
    _id: verificationAliasId(certificateId),
    type: VERIFICATION_ALIAS_TYPE,
    docType: VERIFICATION_ALIAS_TYPE,
    certificateId: String(certificateId || ''),
    tokenHash: hashVerificationToken(token),
    updatedAt: timestamp,
  };
}

/**
 * Constant-time string comparison (used when comparing a presented token with
 * a stored hash).
 */
function constantTimeEquals(a, b) {
  const bufA = Buffer.from(String(a ?? ''), 'utf8');
  const bufB = Buffer.from(String(b ?? ''), 'utf8');
  if (bufA.length !== bufB.length) return false;
  return crypto.timingSafeEqual(bufA, bufB);
}

/**
 * Build a fresh verification record.
 *
 * @param {object} params
 * @param {string} params.token            the raw token (hashed, not stored)
 * @param {string} params.certificateId    the certificate this binds to
 * @param {string} [params.certificateType]
 * @param {string} [params.certificateNumber]
 * @param {string} [params.issuedAt]
 * @param {string} [params.issuedBy]
 * @param {string} [params.now]            ISO timestamp (injectable for tests)
 * @returns {object} the record to persist (contains no raw token)
 */
function buildVerificationRecord({
  token,
  certificateId,
  certificateType = '',
  certificateNumber = '',
  issuedAt = null,
  issuedBy = '',
  now = null,
} = {}) {
  const timestamp = now || new Date().toISOString();
  return {
    _id: verificationRecordId(token),
    type: VERIFICATION_RECORD_TYPE,
    docType: VERIFICATION_RECORD_TYPE,
    certificateId: String(certificateId || ''),
    certificateType: String(certificateType || ''),
    certificateNumber: String(certificateNumber || ''),
    issuedAt: issuedAt || null,
    issuedBy: String(issuedBy || ''),
    // The hash IS the document id; it is repeated as a field for readability
    // and for the idempotent re-mint check.
    tokenHash: hashVerificationToken(token),
    status: 'active',
    revokedAt: null,
    revokedBy: null,
    reprintCount: 0,
    createdAt: timestamp,
    updatedAt: timestamp,
    // Marks the record as produced by this server rather than by a device.
    serverMinted: true,
  };
}

/**
 * True when the record has been revoked.
 * @param {object} record
 * @returns {boolean}
 */
function isRecordRevoked(record) {
  if (!record || typeof record !== 'object') return false;
  if (String(record.status || '').toLowerCase() === 'revoked') return true;
  return Boolean(record.revokedAt);
}

/**
 * Return a copy of the record marked as revoked.
 * @param {object} record
 * @param {object} params
 * @param {string} [params.revokedBy]
 * @param {string} [params.now]
 * @returns {object}
 */
function markRecordRevoked(record, { revokedBy = '', now = null } = {}) {
  const timestamp = now || new Date().toISOString();
  return {
    ...(record || {}),
    status: 'revoked',
    revokedAt: timestamp,
    revokedBy: String(revokedBy || ''),
    updatedAt: timestamp,
  };
}

/**
 * Return a copy of the record with the reprint counter incremented.
 * Reprinting must never create a second identity for the same certificate.
 * @param {object} record
 * @param {object} [params]
 * @param {string} [params.now]
 * @returns {object}
 */
function markRecordReprinted(record, { now = null } = {}) {
  const timestamp = now || new Date().toISOString();
  return {
    ...(record || {}),
    reprintCount: Number((record && record.reprintCount) || 0) + 1,
    lastReprintAt: timestamp,
    updatedAt: timestamp,
  };
}

module.exports = {
  TOKEN_BYTES,
  TOKEN_ENCODING,
  TOKEN_PATTERN,
  VERIFICATION_RECORD_PREFIX,
  VERIFICATION_RECORD_TYPE,
  VERIFICATION_ALIAS_PREFIX,
  VERIFICATION_ALIAS_TYPE,
  generateVerificationToken,
  hashVerificationToken,
  isValidVerificationToken,
  verificationRecordId,
  verificationAliasId,
  buildVerificationAlias,
  constantTimeEquals,
  buildVerificationRecord,
  isRecordRevoked,
  markRecordRevoked,
  markRecordReprinted,
};
